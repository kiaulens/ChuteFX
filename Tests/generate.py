"""Generate the ChuteFX offline tests as Unity editor scripts.

The tests do not reimplement anything: classes and functions are cut verbatim out of Source/ChuteFX.cs and pasted
into the templates in Tests/templates/ (markers /*@NAME@*/). KSP types are replaced by stand-ins, so the tests run
in a plain Unity 2019.4 project without KSP. Run this again after every change to ChuteFX.cs.

Usage:
    python generate.py <unity project>            (or set CHUTEFX_UNITY_PROJECT)
The scripts are written to <unity project>/Assets/Editor/ChuteFXTests/.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC_PATH = os.path.join(HERE, '..', 'Source', 'ChuteFX.cs')
TEMPLATES = os.path.join(HERE, 'templates')

src = open(SRC_PATH, encoding='utf-8').read().replace('\r\n', '\n')


def block(sig):
    """Text from sig up to the matching closing brace."""
    i = src.index(sig)
    k = src.index('{', i)
    depth = 0
    while True:
        if src[k] == '{':
            depth += 1
        elif src[k] == '}':
            depth -= 1
            if depth == 0:
                return src[i:k + 1]
        k += 1


def line(sig):
    i = src.index(sig)
    return src[i:src.index('\n', i)]


def span(start, end):
    return src[src.index(start):src.index(end)]


def fallen_class():
    # KSP types are not available in the editor test
    return (block('    internal class Fallen')
            .replace('public CelestialBody body;', 'public GameObject body;')
            .replace('public ModuleParachute owner;', 'public object owner;')
            .replace('public Part pinPart;', 'public object pinPart;'))


ISLAND = ['        static int Find(int[] par, int x)', '        static void AddEdgeLen(', '        static int StitchIslands(',
          '        static int MeshOwner(', '        static int StitchLayers(']
GROUND = ['        static void Step(', '        static float GroundAt(', '        static float WaveY(',
          '        static List<Vector3> nrmBuf', '        static void ComputeNormals(', '        static void ComputeTurbulence(',
          '        static float InitLayers(', '        static void BuildRenderTopology(', '        static void CountEdge(',
          '        static void SortLong(', '        static void SwapL(', '        static int CountTrue(', '        static void SmoothRender(',
          '        static void RenderNormals(', 'LAYER_FIELDS', '        static long LayerKey(', '        void LayerCloth()',
          '        static void AddEdge(', '        static void AddBend(', '        static void AddEdgeLen(',
          '        static int Find(int[] par, int x)', '        static int StitchIslands(', '        static int MeshOwner(',
          '        static int StitchLayers(']
NORMAL = ['        static void BuildRenderTopology(', '        static void CountEdge(', '        static int CountTrue(',
          '        static void SmoothRender(', '        static void RenderNormals(']


# declarations that fit on one line
SINGLE_LINE = {'        static int Find(int[] par, int x)', '        static List<Vector3> nrmBuf'}


def funcs(sigs):
    out = []
    for s in sigs:
        if s == 'LAYER_FIELDS':
            # fields and helpers of the layer pass (grid constants, buffers, LayerImpact)
            out.append(span('        const float LayerCell = ', '        static long LayerKey('))
        elif s in SINGLE_LINE:
            out.append(line(s))
        else:
            out.append(block(s))
    return '\n\n'.join(out)


TESTS = {
    'ChuteIslandTest.cs': ('island.cs', {'FUNCS': lambda: funcs(ISLAND)}),
    'ChuteGroundTest.cs': ('ground.cs', {'FALLEN': fallen_class, 'CLOTHMESH': lambda: block('    internal class ClothMesh'),
                                         'FUNCS': lambda: funcs(GROUND)}),
    'ChuteNormalTest.cs': ('normal.cs', {'FALLEN': fallen_class, 'CLOTHMESH': lambda: block('    internal class ClothMesh'),
                                         'FUNCS': lambda: funcs(NORMAL)}),
    'ChuteSampleTest.cs': ('sample.cs', {'DEFORMMESH': lambda: block('    internal class DeformMesh')}),
}


def main():
    project = sys.argv[1] if len(sys.argv) > 1 else os.environ.get('CHUTEFX_UNITY_PROJECT')
    if not project or not os.path.isdir(os.path.join(project, 'Assets')):
        sys.exit('usage: python generate.py <unity project>   (or set CHUTEFX_UNITY_PROJECT)')
    out_dir = os.path.join(project, 'Assets', 'Editor', 'ChuteFXTests')
    os.makedirs(out_dir, exist_ok=True)
    for name, (template, parts) in TESTS.items():
        text = open(os.path.join(TEMPLATES, template), encoding='utf-8').read()
        for key, make in parts.items():
            marker = '/*@' + key + '@*/'
            assert marker in text, (template, marker)
            text = text.replace(marker, make())
        header = '// Generated by Tests/generate.py from Source/ChuteFX.cs - do not edit, edit the template instead.\n'
        open(os.path.join(out_dir, name), 'w', encoding='utf-8', newline='\n').write(header + text)
        print('wrote', os.path.join(out_dir, name))


if __name__ == '__main__':
    main()
